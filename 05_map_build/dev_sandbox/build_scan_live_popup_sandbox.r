##         latest point on the daily envelope plot.
## RF051: distinguish Near Normal from No Context in map symbology and
##        print depth/context QA before BRIM integration.
## RF050: sandbox polish for separate depth control / legend boxes,
##        depth selector marker colors based on live-feed depth context JSON,
##        and official station-page link in the popup footer.
## RF049: sandbox polish after first visual QA: map-depth selector JS fix,
