pt_make_depth_tabs <- function(site_code_arg, station_name, active_depth_arg = PLOT_DEPTH_IN) {
  depths <- pt_depth_options_for_site(site_code_arg)

  if (nrow(depths) == 0) {
    return("<div style='font-size:12px; color:#666;'>No depth plots available for this station.</div>")
  }

  active_depth <- if (active_depth_arg %in% depths$depth_in) active_depth_arg else depths$depth_in[1]
  tab_group_id <- pt_safe_id("scan-tabs", site_code_arg)

  buttons <- vapply(seq_len(nrow(depths)), function(i) {
    d <- depths[i, , drop = FALSE]
    panel_id <- pt_safe_id(tab_group_id, d$depth_in)
    active_class <- if (d$depth_in == active_depth) " active" else ""
    paste0(
      "<button type='button' class='scan-depth-tab", active_class, "' data-depth='", as.integer(d$depth_in), "' data-target='", panel_id, "'>",
      "<span class='scan-depth-dot' style='background:", pt_esc(d$depth_color_hex), "'></span>",
      pt_esc(d$depth_label),
      "</button>"
    )
  }, character(1)) |> paste(collapse = "")

  panels <- vapply(seq_len(nrow(depths)), function(i) {
    d <- depths[i, , drop = FALSE]
    panel_id <- pt_safe_id(tab_group_id, d$depth_in)
    active_class <- if (d$depth_in == active_depth) " active" else ""
    paste0(
      "<div id='", panel_id, "' class='scan-depth-panel", active_class, "' data-depth='", as.integer(d$depth_in), "'>",
      pt_make_scan_svg(site_code_arg, station_name, d$depth_in),
      "</div>"
    )
  }, character(1)) |> paste(collapse = "")

  paste0(
    "<div class='scan-depth-tabs' id='", tab_group_id, "'>",
    "<div class='scan-depth-tab-row'>", buttons, "</div>",
    panels,
    "</div>"
  )
}

