pt_make_depth_latest_table <- function(site_code_arg, current_wy_arg = NA_integer_) {
  ## Build the popup's latest-by-depth table locally so we can add a
  ## depth-specific period-of-record column.  The live feed remains the source
  ## of latest values and context labels; the local daily-history RDS supplies
  ## the POR dates used in this sandbox.

  rows <- depth_latest_for_map |>
    dplyr::filter(.data$site_code == site_code_arg) |>
    dplyr::left_join(depth_style, by = "depth_in", suffix = c("", "_style"))

  ## Make suffix-dependent columns explicit so this helper works whether the
  ## live feed already supplied depth labels/colors or they arrived only from
  ## scan_depth_style.csv.
  for (nm in c(
    "depth_order", "depth_order_style",
    "depth_label", "depth_label_style",
    "depth_color_hex", "depth_color_hex_style"
  )) {
    if (!nm %in% names(rows)) rows[[nm]] <- NA
  }

  rows <- rows |>
    dplyr::mutate(
      depth_order = dplyr::coalesce(.data$depth_order, .data$depth_order_style, 999L),
      depth_label = dplyr::coalesce(pt_chr(.data$depth_label), pt_chr(.data$depth_label_style), paste0(.data$depth_in, " in")),
      depth_color_hex = dplyr::coalesce(pt_chr(.data$depth_color_hex), pt_chr(.data$depth_color_hex_style), "#555555")
    ) |>
    dplyr::arrange(.data$depth_order, .data$depth_in)

  if (nrow(rows) == 0) {
    return("<div style='font-size:12px; color:#666;'>No latest depth values available.</div>")
  }

  row_html <- vapply(seq_len(nrow(rows)), function(i) {
    r <- rows[i, , drop = FALSE]

    por <- pt_depth_record_meta(
      site_code_arg = as.integer(site_code_arg),
      depth_in_arg = as.numeric(r$depth_in),
      current_wy_arg = current_wy_arg
    )

    latest_txt <- if (!is.na(r$sms_pct)) paste0(pt_fmt_num(r$sms_pct, 1), "%") else "NA"

    date_txt <- if ("obs_date" %in% names(r) && !is.na(r$obs_date)) {
      as.character(as.Date(r$obs_date))
    } else {
      "NA"
    }

    age_txt <- if ("obs_age_label" %in% names(r) && !is.na(r$obs_age_label)) {
      as.character(r$obs_age_label)
    } else {
      ""
    }

    context_txt <- if ("context_label" %in% names(r) && !is.na(r$context_label)) {
      as.character(r$context_label)
    } else {
      "No context"
    }

    if ("vs_median_pct_points" %in% names(r) && !is.na(r$vs_median_pct_points)) {
      diff_val <- suppressWarnings(as.numeric(r$vs_median_pct_points))
      if (!is.na(diff_val)) {
        context_txt <- paste0(context_txt, " (", ifelse(diff_val > 0, "+", ""), pt_fmt_num(diff_val, 1), " pts vs median)")
      }
    } else if ("display_vs_median_pct_points" %in% names(r) && !is.na(r$display_vs_median_pct_points)) {
      diff_val <- suppressWarnings(as.numeric(r$display_vs_median_pct_points))
      if (!is.na(diff_val)) {
        context_txt <- paste0(context_txt, " (", ifelse(diff_val > 0, "+", ""), pt_fmt_num(diff_val, 1), " pts vs median)")
      }
    }

    if ("n_years" %in% names(r) && !is.na(r$n_years)) {
      context_txt <- paste0(context_txt, "<br><span style='color:#666;'>", as.integer(r$n_years), " yrs</span>")
    }

    paste0(
      "<tr>",
      "<td style='white-space:nowrap; padding:1px 6px 1px 0;'>",
      "<span style='display:inline-block; width:8px; height:8px; border-radius:50%; background:", pt_esc(r$depth_color_hex), "; margin-right:4px;'></span>",
      pt_esc(r$depth_label), "</td>",
      "<td style='text-align:right; white-space:nowrap; padding:1px 8px 1px 0;'>", pt_esc(latest_txt), "</td>",
      "<td style='white-space:nowrap; padding:1px 8px 1px 0;'>", pt_esc(date_txt), "</td>",
      "<td style='white-space:nowrap; padding:1px 8px 1px 0;'>", ifelse(nzchar(age_txt), pt_esc(age_txt), "NA"), "</td>",
      "<td style='padding:1px 8px 1px 0;'>", context_txt, "</td>",
      "<td style='white-space:nowrap; padding:1px 0;'>", pt_esc(por$record_label[1]), "</td>",
      "</tr>"
    )
  }, character(1))

  paste0(
    "<table style='font-size:12px; border-collapse:collapse;'>",
    "<thead><tr>",
    "<th style='text-align:left; padding-right:6px;'>Depth</th>",
    "<th style='text-align:right; padding-right:8px;'>Latest</th>",
    "<th style='text-align:left; padding-right:8px;'>Date</th>",
    "<th style='text-align:left; padding-right:8px;'>Age</th>",
    "<th style='text-align:left; padding-right:8px;'>Historical context</th>",
    "<th style='text-align:left;'>Record</th>",
    "</tr></thead><tbody>",
    paste(row_html, collapse = ""),
    "</tbody></table>"
  )
}

pt_make_scan_svg <- function(site_code_arg, station_name, depth_in_arg = PLOT_DEPTH_IN) {

  p <- percentiles |>
    dplyr::filter(.data$site_code == site_code_arg, .data$depth_in == depth_in_arg) |>
    dplyr::arrange(.data$water_day)

  tr <- trace |>
    dplyr::filter(.data$site_code == site_code_arg, .data$depth_in == depth_in_arg) |>
    dplyr::arrange(.data$water_day)

  current_wy <- pt_trace_current_wy(tr)
  daily_record_meta <- pt_depth_record_meta(site_code_arg, depth_in_arg, current_wy)

  ## Use daily ribbons only where enough historical years support the
  ## station/depth/day envelope.  Very new stations still show their current-WY
  ## trace but do not pretend to have a stable climatological envelope.
  p_for_ribbons <- p
  if ("n_years" %in% names(p_for_ribbons)) {
    p_for_ribbons <- p_for_ribbons |>
      dplyr::filter(!is.na(.data$n_years), .data$n_years >= DAILY_RIBBON_MIN_YEARS)
  } else {
    p_for_ribbons <- p_for_ribbons[0, , drop = FALSE]
  }
  daily_context_ok <- nrow(p_for_ribbons) >= 30
  daily_years_min <- if (nrow(p) > 0 && "n_years" %in% names(p)) {
    suppressWarnings(min(p$n_years, na.rm = TRUE))
  } else {
    NA_integer_
  }
  daily_years_max <- if (nrow(p) > 0 && "n_years" %in% names(p)) {
    suppressWarnings(max(p$n_years, na.rm = TRUE))
  } else {
    NA_integer_
  }

  style_row <- depth_style |>
    dplyr::filter(.data$depth_in == depth_in_arg) |>
    dplyr::slice(1)

  depth_label <- if (nrow(style_row) > 0 && !is.na(style_row$depth_label[1])) {
    style_row$depth_label[1]
  } else {
    paste0(depth_in_arg, " in")
  }

  depth_color <- if (nrow(style_row) > 0 && !is.na(style_row$depth_color_hex[1])) {
    style_row$depth_color_hex[1]
  } else {
    "#333333"
  }

  if (nrow(tr) == 0) {
    return(paste0(
      "<div style='font-size:12px; color:#666; border-left:4px solid ", depth_color, "; padding-left:6px;'>",
      "No current-water-year plot data available for ", pt_esc(depth_label), " at this station.</div>"
    ))
  }

  recent_ctx <- pt_build_recent_monthly_context(site_code_arg, depth_in_arg)
  recent_actual <- recent_ctx$actual
  recent_ref <- recent_ctx$ref
  recent_meta <- recent_ctx$meta

  w <- SVG_WIDTH
  h <- SVG_HEIGHT
  ml <- 46
  mr <- 14
  mt <- 22
  context_h <- if (nrow(recent_actual) >= 3) 86 else 0
  gap <- if (context_h > 0) 14 else 0
  plot_top <- mt + context_h + gap
  mb <- 34
  plot_h <- h - plot_top - mb
  plot_w <- w - ml - mr

  vals <- if (daily_context_ok) {
    c(p_for_ribbons$p00, p_for_ribbons$p10, p_for_ribbons$p30, p_for_ribbons$p50, p_for_ribbons$p70, p_for_ribbons$p90, p_for_ribbons$p100, tr$sms_pct)
  } else {
    c(tr$sms_pct)
  }
  vals <- vals[is.finite(vals)]
  y_min <- max(0, floor(min(vals, na.rm = TRUE) / 5) * 5)
  y_max <- ceiling(max(vals, na.rm = TRUE) / 5) * 5
  if (!is.finite(y_min) || !is.finite(y_max) || y_min == y_max) {
    y_min <- 0
    y_max <- 50
  }

  xf <- function(x) ml + ((x - 1) / 365) * plot_w
  yf <- function(y) plot_top + plot_h - ((y - y_min) / (y_max - y_min)) * plot_h

  month_ticks <- pt_month_ticks()

  ribbon_defs <- tibble::tribble(
    ~lo,  ~hi,    ~fill,      ~label,
    "p00", "p10", "#EAD6B8", "min-p10",
    "p10", "p30", "#F4EAD8", "p10-p30",
    "p30", "p70", "#ECECEC", "p30-p70",
    "p70", "p90", "#DDEEF7", "p70-p90",
    "p90", "p100", "#BFD7EA", "p90-max"
  )

  ribbons <- if (daily_context_ok) {
    purrr::pmap_chr(ribbon_defs, function(lo, hi, fill, label) {
      pts <- pt_svg_ribbon_polygon(p_for_ribbons, lo, hi, xf, yf)
      if (!nzchar(pts)) return("")
      paste0("<polygon points='", pts, "' fill='", fill, "' opacity='0.95'/>")
    }) |> paste(collapse = "")
  } else {
    ""
  }

  median_pts <- if (daily_context_ok) pt_svg_line(p_for_ribbons, "water_day", "p50", xf, yf) else ""
  median_line <- if (nzchar(median_pts)) {
    paste0("<polyline points='", median_pts, "' fill='none' stroke='#666666' stroke-width='1.2' stroke-dasharray='3 3'/>")
  } else ""

  trace_pts <- pt_svg_line(tr, "water_day", "sms_pct", xf, yf)
  trace_line <- if (nzchar(trace_pts)) {
    paste0("<polyline points='", trace_pts, "' fill='none' stroke='#111111' stroke-width='2.2'/>")
  } else ""

  latest_pt <- tr |> dplyr::filter(.data$obs_date == max(.data$obs_date, na.rm = TRUE)) |> dplyr::slice(1)
  latest_dot <- if (nrow(latest_pt) == 1) {
    ## RF055c: match the latest daily marker to the selected depth color,
    ## while leaving the current-WY trace line black for contrast.
    paste0(
      "<circle cx='", round(xf(latest_pt$water_day), 1), "' cy='", round(yf(latest_pt$sms_pct), 1),
      "' r='3.8' fill='", depth_color, "' stroke='white' stroke-width='1'/>")
  } else ""

  y_ticks <- pretty(c(y_min, y_max), n = 4)
  y_ticks <- y_ticks[y_ticks >= y_min & y_ticks <= y_max]

  ## RF048: keep y-axis tick labels only.  Full-width grid lines were
  ## visually distracting in the small popup plot and competed with the
  ## translucent percentile ribbons.
  grid <- paste0(
    purrr::map_chr(y_ticks, function(yy) {
      paste0(
        "<text x='", ml - 6, "' y='", round(yf(yy) + 4, 1), "' text-anchor='end' font-size='10' fill='#555'>", yy, "</text>"
      )
    }),
    collapse = ""
  )

  x_axis <- paste0(
    purrr::pmap_chr(month_ticks, function(water_day, label) {
      paste0(
        "<line x1='", round(xf(water_day), 1), "' x2='", round(xf(water_day), 1), "' y1='", plot_top + plot_h,
        "' y2='", plot_top + plot_h + 4, "' stroke='#555'/>",
        "<text x='", round(xf(water_day), 1), "' y='", plot_top + plot_h + 17, "' text-anchor='middle' font-size='10' fill='#555'>", label, "</text>"
      )
    }),
    collapse = ""
  )

  context_svg <- ""
  if (nrow(recent_actual) >= 3) {
    cx0 <- ml
    cy0 <- mt + 16
    ch <- context_h - 34
    cw <- plot_w

    c_dates <- as.numeric(recent_actual$month_date)
    c_min_date <- min(c_dates, na.rm = TRUE)
    c_max_date <- max(c_dates, na.rm = TRUE)

    recent_ref_by_month <- recent_ref |>
      dplyr::mutate(calendar_month = suppressWarnings(as.integer(.data$calendar_month))) |>
      dplyr::filter(
        !is.na(.data$calendar_month),
        !is.na(.data$ref_p30),
        !is.na(.data$ref_p50),
        !is.na(.data$ref_p70)
      ) |>
      dplyr::distinct(.data$calendar_month, .keep_all = TRUE) |>
      dplyr::select("calendar_month", "ref_p30", "ref_p50", "ref_p70")

    ref_month_seq <- seq.Date(
      from = as.Date(format(min(recent_actual$month_date, na.rm = TRUE), "%Y-%m-01")),
      to = as.Date(format(max(recent_actual$month_date, na.rm = TRUE), "%Y-%m-01")),
      by = "month"
    )

    recent_ref_plot <- tibble::tibble(
      month_date = ref_month_seq,
      calendar_month = lubridate::month(ref_month_seq)
    ) |>
      dplyr::left_join(recent_ref_by_month, by = "calendar_month") |>
      dplyr::filter(!is.na(.data$ref_p50)) |>
      dplyr::arrange(.data$month_date)

    ref_vals <- if (nrow(recent_ref_plot) > 0) c(recent_ref_plot$ref_p30, recent_ref_plot$ref_p50, recent_ref_plot$ref_p70) else numeric(0)
    c_vals <- c(recent_actual$actual_sms_pct, ref_vals)
    c_vals <- c_vals[is.finite(c_vals)]

    c_y_min <- max(0, floor(min(c_vals, na.rm = TRUE) / 5) * 5)
    c_y_max <- ceiling(max(c_vals, na.rm = TRUE) / 5) * 5
    if (!is.finite(c_y_min) || !is.finite(c_y_max) || c_y_min == c_y_max) {
      c_y_min <- y_min
      c_y_max <- y_max
    }

    cxf <- function(d) cx0 + ((as.numeric(d) - c_min_date) / max(1, c_max_date - c_min_date)) * cw
    cyf <- function(y) cy0 + ch - ((y - c_y_min) / (c_y_max - c_y_min)) * ch

    ## Historical monthly reference band and median, repeated across the recent
    ## monthly time axis.  This is shown only where the station/depth has enough
    ## years to support a stable reference trace.
    ref_band <- ""
    ref_line <- ""
    ref_note <- paste0("Monthly stats shown where ≥", CONTEXT_STAT_MIN_YEARS, " years support the reference")

    if (nrow(recent_ref_plot) >= 3) {
      ref_band_pts <- paste(
        c(
          paste0(
            format(round(cxf(recent_ref_plot$month_date), 1), trim = TRUE), ",",
            format(round(cyf(recent_ref_plot$ref_p30), 1), trim = TRUE)
          ),
          paste0(
            format(round(rev(cxf(recent_ref_plot$month_date)), 1), trim = TRUE), ",",
            format(round(rev(cyf(recent_ref_plot$ref_p70)), 1), trim = TRUE)
          )
        ),
        collapse = " "
      )
      ref_band <- paste0("<polygon points='", ref_band_pts, "' fill='#D9D9D9' opacity='0.42'/>")

      ref_pts <- pt_svg_line(recent_ref_plot, "month_date", "ref_p50", cxf, cyf)
      if (nzchar(ref_pts)) {
        ref_line <- paste0("<polyline points='", ref_pts, "' fill='none' stroke='#666666' stroke-width='1.1' stroke-dasharray='4 3'/>")
      }
    } else {
      ref_note <- paste0("Actual monthly values shown; monthly reference hidden because <", CONTEXT_STAT_MIN_YEARS, " years are available")
    }

    actual_line_pts <- pt_svg_line(recent_actual, "month_date", "actual_sms_pct", cxf, cyf)
    actual_line <- if (nzchar(actual_line_pts)) {
      paste0("<polyline points='", actual_line_pts, "' fill='none' stroke='#111111' stroke-width='1.7'/>")
    } else ""

    ## RF055c: add small monthly point markers so gaps in the recent context
    ## trace are visually obvious instead of looking like flat/constant data.
    actual_points <- if (nrow(recent_actual) > 0) {
      paste0(
