pt_depth_values_from_latest <- function(latest_df) {
  if (!"depth_values_json" %in% names(latest_df)) return(tibble::tibble())

  purrr::map_dfr(seq_len(nrow(latest_df)), function(i) {
    raw_json <- latest_df$depth_values_json[[i]]
    raw_json <- if (is.null(raw_json) || length(raw_json) == 0) NA_character_ else as.character(raw_json[[1]])
    if (is.na(raw_json) || !nzchar(raw_json)) return(tibble::tibble())

    vals <- tryCatch(
      jsonlite::fromJSON(raw_json, simplifyDataFrame = TRUE),
      error = function(e) NULL
    )
    if (is.null(vals) || length(vals) == 0) return(tibble::tibble())

    vals <- tibble::as_tibble(vals)
    if (nrow(vals) == 0) return(tibble::tibble())

    vals |>
      dplyr::mutate(
        site_code = suppressWarnings(as.integer(latest_df$site_code[[i]])),
        station_name = if (!is.na(latest_name_col)) {
          as.character(latest_df[[latest_name_col]][[i]])
        } else {
          paste0("Site ", latest_df$site_code[[i]])
        }
      )
  })
}

