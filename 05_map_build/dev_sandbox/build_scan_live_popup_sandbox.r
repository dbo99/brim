pt_context_fill <- function(x) {
  dplyr::case_when(
    x == "Much below normal" ~ "#8C510A",
    x == "Below normal"      ~ "#D8B365",
    x == "Near normal"       ~ "#7F7F7F",
    x == "Above normal"      ~ "#92C5DE",
    x == "Much above normal" ~ "#2166AC",
    TRUE                     ~ "#FFFFFF"
  )
}

pt_context_fill_opacity <- function(x) {
  dplyr::case_when(
    is.na(x) ~ 0,
    x == "No context" ~ 0,
    TRUE ~ 0.88
  )
}

pt_context_label <- function(sms_pct, p10, p30, p70, p90) {
  dplyr::case_when(
    is.na(sms_pct) | is.na(p10) | is.na(p30) | is.na(p70) | is.na(p90) ~ "No context",
    sms_pct <= p10 ~ "Much below normal",
    sms_pct <= p30 ~ "Below normal",
    sms_pct <= p70 ~ "Near normal",
    sms_pct <= p90 ~ "Above normal",
    sms_pct >  p90 ~ "Much above normal",
    TRUE ~ "No context"
  )
}


pt_scan_hover_html <- function(station_name, depth_label, sms_pct, context_label, age_label) {
  ## Keep hover text short but readable.  Four explicit rows are easier to scan
  ## than a single long line that wraps unpredictably in Leaflet tooltips.
  paste0(
    "<strong>", pt_esc(station_name), "</strong><br/>",
    pt_esc(depth_label), ": ", pt_esc(pt_fmt_num(sms_pct, 1)), "%<br/>",
    pt_esc(context_label), "<br/>",
    "Age: ", pt_esc(age_label)
  )
}

pt_fmt_mon_year <- function(x) {
  x <- as.Date(x)
  ifelse(is.na(x), "NA", format(x, "%b %Y"))
}

pt_fmt_wy_range <- function(wy_min, wy_max) {
  wy_min <- suppressWarnings(as.integer(wy_min))
  wy_max <- suppressWarnings(as.integer(wy_max))
  if (is.na(wy_min) || is.na(wy_max)) return("WY record unavailable")
  paste0("WY", wy_min, "–WY", wy_max)
}

pt_depth_record_meta <- function(site_code_arg, depth_in_arg, current_wy_arg = NA_integer_) {
  ## Depth-specific records can differ because sensors are installed, replaced,
  ## or retired independently.  This helper keeps the popup table and plot notes
  ## honest about the period of record / period of analysis for each depth.
  empty <- tibble::tibble(
    first_date = as.Date(NA),
    last_date = as.Date(NA),
    first_wy = NA_integer_,
    last_wy = NA_integer_,
    analysis_first_wy = NA_integer_,
    analysis_last_wy = NA_integer_,
    record_label = "Not available",
    analysis_label = "POA unavailable"
  )

  if (is.null(daily_history)) return(empty)

  x <- daily_history |>
    dplyr::filter(
      .data$site_code == site_code_arg,
      .data$depth_in == depth_in_arg,
      !is.na(.data$date),
      !is.na(.data$sms_pct)
    )

  if (nrow(x) == 0) return(empty)

  first_date <- min(x$date, na.rm = TRUE)
  last_date <- max(x$date, na.rm = TRUE)
  first_wy <- suppressWarnings(min(x$water_year, na.rm = TRUE))
  last_wy <- suppressWarnings(max(x$water_year, na.rm = TRUE))

  current_wy_arg <- suppressWarnings(as.integer(current_wy_arg))
  analysis_x <- x
  if (!is.na(current_wy_arg) && is.finite(current_wy_arg)) {
    analysis_x <- analysis_x |> dplyr::filter(.data$water_year < current_wy_arg)
  }

  if (nrow(analysis_x) > 0) {
    analysis_first_wy <- suppressWarnings(min(analysis_x$water_year, na.rm = TRUE))
    analysis_last_wy  <- suppressWarnings(max(analysis_x$water_year, na.rm = TRUE))
  } else {
    analysis_first_wy <- NA_integer_
    analysis_last_wy  <- NA_integer_
  }

  tibble::tibble(
    first_date = first_date,
    last_date = last_date,
    first_wy = first_wy,
    last_wy = last_wy,
    analysis_first_wy = analysis_first_wy,
    analysis_last_wy = analysis_last_wy,
    record_label = paste0(pt_fmt_mon_year(first_date), "–", pt_fmt_mon_year(last_date)),
    analysis_label = if (!is.na(analysis_first_wy) && !is.na(analysis_last_wy)) {
      paste0("WY", analysis_first_wy, "–WY", analysis_last_wy)
    } else {
      "POA unavailable"
    }
  )
}

pt_trace_current_wy <- function(tr) {
  if ("water_year" %in% names(tr)) {
    wy <- suppressWarnings(max(as.integer(tr$water_year), na.rm = TRUE))
    if (is.finite(wy)) return(as.integer(wy))
  }
  if ("obs_date" %in% names(tr) && any(!is.na(tr$obs_date))) {
    d <- max(as.Date(tr$obs_date), na.rm = TRUE)
    yr <- lubridate::year(d)
    mo <- lubridate::month(d)
    return(as.integer(ifelse(mo >= 10, yr + 1, yr)))
  }
  NA_integer_
}

pt_safe_id <- function(...) {
  x <- paste(..., sep = "-")
  x <- gsub("[^A-Za-z0-9_-]+", "-", x)
  x <- gsub("-+", "-", x)
  x
}

