##        and short-record handling for daily ribbon context.
## RF048d: full overwrite of sandbox script; removes stray split(.$site_code).
##
## PURPOSE:
##   Build a small, fast Leaflet sandbox for developing BRIM Ops Live SCAN
##   popup/hover/plot design without rebuilding the full BRIM HTML map.
## RF051c: near-normal legend, hollow no-context symbols, and multiline HTML tooltips.
## RF054: POR/POA labeling cleanup, depth-record table column, and lower plot title.
