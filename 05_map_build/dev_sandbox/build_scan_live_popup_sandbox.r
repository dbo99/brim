pt_build_recent_monthly_context <- function(site_code_arg, depth_in_arg) {
  ## Purpose:
  ##   Build a simple, intuitive recent-history context plot dataset.
  ##
  ## Design:
  ##   - Actual recent/available record is monthly median soil moisture.
  ##   - Historical monthly reference statistics are added only when enough
  ##     water years are available.  This avoids implying a climatological norm
  ##     from a station with only a few years of data.
  ##   - Current WY is excluded from the historical reference statistics.

  if (is.null(daily_history)) {
    return(list(actual = tibble::tibble(), ref = tibble::tibble(), meta = tibble::tibble()))
  }

  x <- daily_history |>
    dplyr::filter(
      .data$site_code == site_code_arg,
      .data$depth_in == depth_in_arg,
      !is.na(.data$date),
      !is.na(.data$sms_pct)
    ) |>
    dplyr::mutate(
      calendar_month = lubridate::month(.data$date),
      month_date = as.Date(format(.data$date, "%Y-%m-01"))
    )

  if (nrow(x) == 0) {
    return(list(actual = tibble::tibble(), ref = tibble::tibble(), meta = tibble::tibble()))
  }

  max_date <- max(x$date, na.rm = TRUE)
  first_date <- min(x$date, na.rm = TRUE)
  start_date <- as.Date(max_date %m-% lubridate::years(CONTEXT_YEARS_BACK))
  actual_start_date <- max(start_date, first_date, na.rm = TRUE)

  actual <- x |>
    dplyr::filter(.data$date >= actual_start_date) |>
    dplyr::group_by(.data$month_date, .data$calendar_month) |>
    dplyr::summarise(
      actual_sms_pct = stats::median(.data$sms_pct, na.rm = TRUE),
      n_days = dplyr::n(),
      .groups = "drop"
    ) |>
    dplyr::filter(.data$n_days >= 5, !is.na(.data$actual_sms_pct)) |>
    dplyr::arrange(.data$month_date)

  current_wy <- if ("water_year" %in% names(x)) max(x$water_year, na.rm = TRUE) else NA_integer_

  hist_ref <- x
  if (!is.na(current_wy) && is.finite(current_wy)) {
    hist_ref <- hist_ref |> dplyr::filter(.data$water_year < current_wy)
  }

  ref <- hist_ref |>
    dplyr::group_by(.data$calendar_month) |>
    dplyr::summarise(
      ref_p30 = as.numeric(stats::quantile(.data$sms_pct, 0.30, na.rm = TRUE, names = FALSE)),
      ref_p50 = stats::median(.data$sms_pct, na.rm = TRUE),
      ref_p70 = as.numeric(stats::quantile(.data$sms_pct, 0.70, na.rm = TRUE, names = FALSE)),
      ref_n_years = dplyr::n_distinct(.data$water_year[!is.na(.data$sms_pct)]),
      .groups = "drop"
    ) |>
    dplyr::filter(.data$ref_n_years >= CONTEXT_STAT_MIN_YEARS)

  ## Return the monthly reference as one row per calendar month.  Plot A later
  ## expands this into a complete repeating monthly reference sequence across
  ## the displayed years; do not join the reference to sparse actual months here.
  actual_years <- unique(lubridate::year(actual$month_date))
  ref_ok <- nrow(ref) >= 3

  meta <- tibble::tibble(
    first_date = first_date,
    last_date = max_date,
    actual_start_date = actual_start_date,
    actual_end_date = max_date,
    actual_n_months = nrow(actual),
    actual_n_years = length(actual_years),
    ref_ok = ref_ok,
    ref_min_years = if (nrow(ref) > 0) min(ref$ref_n_years, na.rm = TRUE) else NA_integer_,
    ref_max_years = if (nrow(ref) > 0) max(ref$ref_n_years, na.rm = TRUE) else NA_integer_,
    ref_first_date = if (nrow(hist_ref) > 0) min(hist_ref$date, na.rm = TRUE) else as.Date(NA),
    ref_last_date  = if (nrow(hist_ref) > 0) max(hist_ref$date, na.rm = TRUE) else as.Date(NA),
    ref_first_wy = if (nrow(hist_ref) > 0) suppressWarnings(min(hist_ref$water_year, na.rm = TRUE)) else NA_integer_,
    ref_last_wy  = if (nrow(hist_ref) > 0) suppressWarnings(max(hist_ref$water_year, na.rm = TRUE)) else NA_integer_
  )

  list(actual = actual, ref = ref, meta = meta)
}

